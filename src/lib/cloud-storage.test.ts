import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

beforeEach(() => vi.resetModules())
afterEach(() => { vi.doUnmock('./providers'); vi.doUnmock('./providers/cloudbase'); vi.doUnmock('./providers/supabase'); vi.doUnmock('./local-trash'); vi.restoreAllMocks() })

describe('selected provider loading and deferred subscriptions', () => {
  it('imports neither SDK for synchronous MIME helpers and imports only the selected backend on demand', async () => {
    const cloudbaseLoad = vi.fn()
    const supabaseLoad = vi.fn()
    const getSession = vi.fn(async () => ({ user: { id: 'member' } }))
    vi.doMock('./providers', () => ({ dataProvider: 'cloudbase' }))
    vi.doMock('./providers/cloudbase', () => { cloudbaseLoad(); return { getCloudSession: getSession } })
    vi.doMock('./providers/supabase', () => { supabaseLoad(); return {} })
    const api = await import('./cloud-storage')
    expect(api.extensionForMime('image/jpeg', 'a.png')).toBe('jpg')
    expect(cloudbaseLoad).not.toHaveBeenCalled()
    expect(supabaseLoad).not.toHaveBeenCalled()
    await expect(api.getCloudSession()).resolves.toEqual({ user: { id: 'member' } })
    await api.getCloudSession()
    expect(cloudbaseLoad).toHaveBeenCalledOnce()
    expect(supabaseLoad).not.toHaveBeenCalled()
  })

  it('does not install a subscription closed before backend import finishes', async () => {
    let release!: () => void
    const gate = new Promise<void>((resolve) => { release = resolve })
    const authStart = vi.fn(() => vi.fn())
    const watchStart = vi.fn(() => ({ close: vi.fn() }))
    vi.doMock('./providers', () => ({ dataProvider: 'cloudbase' }))
    vi.doMock('./providers/cloudbase', async () => { await gate; return { onCloudAuthChange: authStart, subscribeToCloudWorkspace: watchStart, getCloudSession: async () => null } })
    const api = await import('./cloud-storage')
    const stopAuth = api.onCloudAuthChange(vi.fn())
    const watch = api.subscribeToCloudWorkspace('space', vi.fn())
    stopAuth()
    const closed = watch.close()
    release()
    await api.getCloudSession()
    await closed
    expect(authStart).not.toHaveBeenCalled()
    expect(watchStart).not.toHaveBeenCalled()
  })

  it('closes a loaded subscription once even after repeated cleanup', async () => {
    const close = vi.fn()
    const start = vi.fn(() => ({ close }))
    vi.doMock('./providers', () => ({ dataProvider: 'supabase' }))
    vi.doMock('./providers/supabase', () => ({ subscribeToCloudWorkspace: start, getCloudSession: async () => null }))
    const api = await import('./cloud-storage')
    const handle = api.subscribeToCloudWorkspace('space', vi.fn())
    await api.getCloudSession()
    expect(start).toHaveBeenCalledWith('space', expect.any(Function))
    await handle.close()
    await handle.close()
    expect(close).toHaveBeenCalledOnce()
  })

  it('routes local recycle-bin operations without loading cloud SDKs', async () => {
    const list = vi.fn(async () => [])
    const restore = vi.fn(async () => {})
    const purge = vi.fn(async () => {})
    const cloud = vi.fn()
    vi.doMock('./providers', () => ({ dataProvider: 'local' }))
    vi.doMock('./local-trash', () => ({ listLocalTrash: list, restoreLocalTrash: restore, purgeLocalTrash: purge }))
    vi.doMock('./providers/cloudbase', () => { cloud(); return {} })
    vi.doMock('./providers/supabase', () => { cloud(); return {} })
    const api = await import('./cloud-storage')
    await api.listCloudTrash('local')
    await api.restoreCloudTrash('local', 'one')
    await api.purgeCloudTrash('local', 'one')
    expect(list).toHaveBeenCalledWith('local')
    expect(restore).toHaveBeenCalledWith('local', 'one')
    expect(purge).toHaveBeenCalledWith('local', 'one')
    expect(cloud).not.toHaveBeenCalled()
  })
})
